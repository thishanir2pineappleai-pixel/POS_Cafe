import { Fragment, useEffect, useMemo, useState } from 'react';
import { saveBlob } from '../../api/client.js';
import { attempt } from '../../api/errorHandler.js';
import * as orderApi from '../../api/orderApi.js';
import * as reportsApi from '../../api/reportsApi.js';
import ManageDiscountButton from '../../components/buttons/ManageDiscountButton.jsx';
import ErrorState from '../../components/common/ErrorState.jsx';
import { ChevronRightIcon } from '../../components/common/Icons.jsx';
import LoadingState from '../../components/common/LoadingState.jsx';
import Pagination from '../../components/common/Pagination.jsx';
import DateFilter from '../../components/filters/DateFilter.jsx';
import DateRangePicker from '../../components/filters/DateRangePicker.jsx';
import { useDebounced } from '../../hooks/useDebounced.js';
import { useResource } from '../../hooks/useResource.js';
import MainLayout from '../../layout/MainLayout.jsx';
import { toISO } from '../../api/formatDate.js';
import ManageDiscount from './ManageDiscount.jsx';
import SalesOrders from './SalesOrders.jsx';
import SalesSummary from './SalesSummary.jsx';
import { ORDERS_PAGE_SIZE } from './salesFormat.js';

// An order as the table shows it.
const toRow = (o) => ({ id: o.orderId, type: o.type, customer: o.customer ?? '-', items: o.itemsText, total: o.total, status: o.status, time: o.time, date: o.date });

// Orders and the four summary numbers for the chosen dates come from the Sales Service (through the Gateway).
export default function SalesManagement() {
  const today = useMemo(() => new Date(), []);
  const todayRange = useMemo(() => ({ start: today, end: today }), [today]);
  const [screen, setScreen] = useState('dashboard'); // dashboard | discounts
  const [range, setRange] = useState(todayRange);
  const [picking, setPicking] = useState(false);
  const [query, setQuery] = useState('');
  const search = useDebounced(query);
  const [page, setPage] = useState(1);
  const [notice, setNotice] = useState('');

  const from = toISO(range.start);
  const to = toISO(range.end ?? range.start);
  const orders = useResource((signal) => orderApi.listOrders({ from, to, search, page, limit: ORDERS_PAGE_SIZE }, signal), [from, to, search, page]);
  const summary = useResource((signal) => reportsApi.salesSummary({ from, to }, signal), [from, to]);

  const totalPages = orders.data?.meta?.totalPages ?? 1;
  useEffect(() => { if (page > totalPages) setPage(totalPages); }, [page, totalPages]);

  const applyRange = (next) => { setRange(next); setPicking(false); setPage(1); };
  const updateQuery = (value) => { setQuery(value); setPage(1); };

  // CSV is generated by the server for every order that matches the filters (not only the page). The server does not
  // produce PDF or XLS yet (it answers 501), so those choices say so instead of handing over a differently built file.
  const exportOrders = async (format) => {
    if (format !== 'csv') { setNotice('Only the CSV export is available at the moment.'); return; }
    setNotice('');
    const result = await attempt(() => orderApi.exportOrders({ from, to, search }));
    if (result.ok) saveBlob(result.data.blob, result.data.filename ?? 'sales-orders.csv');
    else setNotice(result.error);
  };

  const discounts = screen === 'discounts';
  const title = discounts
    ? <>{['Sales Management', 'Manage Discount'].map((p, i) => <Fragment key={p}>{i > 0 && <ChevronRightIcon size={22} className="title-sep" />}{p}</Fragment>)}</>
    : 'Sales Management';
  const subtitle = discounts ? 'Create, manage, organize and apply discounts.' : 'Easily track, analyze, and export your sales data.';

  return (
    <MainLayout title={title} subtitle={subtitle} active="Sales Management">
      {!discounts && (
        <>
          <section className="panel sales-top">
            <div>
              <div className="sales-top__label">Select Date / Date Range</div>
              <DateFilter range={range} today={today} onOpen={() => setPicking(true)} onReset={() => applyRange(todayRange)} />
            </div>
            <ManageDiscountButton onClick={() => setScreen('discounts')} />
          </section>

          {summary.error && <ErrorState message={summary.error} onRetry={summary.reload} />}
          <SalesSummary summary={summary.data} />
          {notice && <ErrorState message={notice} />}
          {orders.loading && !orders.data && <LoadingState message="Loading orders..." />}
          {orders.error && <ErrorState message={orders.error} onRetry={orders.reload} />}
          {orders.data && <SalesOrders orders={orders.data.data.map(toRow)} query={query} onQuery={updateQuery} onExport={exportOrders} />}
          {orders.data && <Pagination page={page} pageSize={ORDERS_PAGE_SIZE} total={orders.data.meta.total} onChange={setPage} label="orders" />}

          {picking && (
            <DateRangePicker start={range.start} end={range.end} today={today} onApply={applyRange} onCancel={() => setPicking(false)} />
          )}
        </>
      )}
      {discounts && <ManageDiscount onBack={() => setScreen('dashboard')} today={today} />}
    </MainLayout>
  );
}
